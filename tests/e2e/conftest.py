"""Фикстуры дымовых E2E-сценариев.

E2E проверяют маршруты через настоящий браузер, поэтому им нужен живой
HTTP-сервер, а не ``TestClient``. Сервер поднимается в потоке того же
процесса - только так подмены из ``tests/conftest.py`` (изоляция
хранилища, фикстура ``parsed_page``) продолжают действовать: они меняют
атрибуты модулей, а модули у сервера и у теста общие.

Отдельный процесс потребовал бы передавать каталог данных через
переменную окружения, то есть заводить в ``storage`` настройку, нужную
только тестам. Такой настройки нет и заводить её ради тестов не стоит.
"""

import os
import socket
import threading
import time

import pytest
import uvicorn
from playwright.sync_api import Error as PlaywrightError

import main

E2E_REQUIRED_ENV = "E2E_REQUIRED"
"""Имя переменной, которой окружение объявляет браузерный слой обязательным.

Ставится в CI (``.github/workflows/ci.yml``) сразу после шага установки
браузера. На машине разработчика не ставится никогда.
"""


@pytest.fixture(scope="session")
def browser(launch_browser):
    """Один браузер на весь прогон; замещает фикстуру плагина.

    Имя выбрано не для красоты: так называется сессионная фикстура
    pytest-playwright, и объявление здесь её замещает.

    Запускает плагинная ``launch_browser``, а не ``chromium.launch()``.

    С :data:`E2E_REQUIRED_ENV` пропуск
    превращается в падение с той же причиной.
    """
    try:
        browser = launch_browser()
    except PlaywrightError as e:
        # Диагноз не ставится: сюда попадает любой сбой запуска, а не
        # только отсутствие браузера. Ложное «не установлен» отправляет
        # человека выполнять `playwright install`, который не поможет.
        reason = f"браузер не запустился (при необходимости `playwright install chromium`): {e}"
        if os.environ.get(E2E_REQUIRED_ENV):
            # pytrace=False: стек pytest-а тут не помогает, причина в тексте.
            pytest.fail(reason, pytrace=False)
        pytest.skip(reason)
    yield browser
    browser.close()


@pytest.fixture
def live_server(data_dir):
    """Поднимает приложение на свободном порту и отдаёт его базовый адрес.

    Порт выбирает ядро (``bind`` на 0), иначе параллельные прогоны и
    занятый 8000-й делали бы сценарии мигающими.

    Занятый сокет отдаётся серверу, а не закрывается ради номера порта.
    Окно между проверкой и использованием закрывается тем, что
    проверки и не происходит: сокет всё время один и тот же.

    Ожидание готовности - единственное место во всём наборе, где есть
    ``sleep``: у ``uvicorn.Server`` нет события «поднялся», а обращаться
    к серверу до старта нельзя. Это опрос флага: цикл выходит сразу, как только сервер готов.
    """
    sock = socket.socket()
    # Сокет закрывает уже поднявшийся uvicorn: `shutdown(sockets=...)`.
    # До этого момента он ничей, и любой отказ по дороге оставлял бы его открытым: оба
    # утверждения ниже уводят фикстуру из подготовки, поэтому ни разборка
    # после yield, ни shutdown сервера не выполняются. При
    # `filterwarnings = error` незакрытый сокет краснеет не здесь, а у
    # случайного соседа, которого выберет порядок pytest-randomly.
    try:
        sock.bind(("127.0.0.1", 0))
        port = sock.getsockname()[1]

        # Настройки минимальны намеренно: сервер поднимается теми же
        # умолчаниями, что и прод (`uvicorn main:app`), иначе E2E проверяли бы
        # конфигурацию, которой в бою нет. `host`/`port` остаются: сокет свой,
        # но адрес из них берут логи и строка, которую фикстура отдаёт тесту.
        server = uvicorn.Server(
            uvicorn.Config(main.app, host="127.0.0.1", port=port, log_level="warning")
        )
        thread = threading.Thread(target=server.run, kwargs={"sockets": [sock]}, daemon=True)
        thread.start()

        deadline = time.monotonic() + 10
        while not server.started:
            # Живость потока проверяется первой: упавший сервер иначе означал
            # бы десять секунд ожидания на каждый сценарий и сообщение
            # «не поднялся» вместо настоящей причины.
            assert thread.is_alive(), "поток сервера упал на старте, причина в логе выше"
            assert time.monotonic() < deadline, "сервер не поднялся за 10 секунд"
            time.sleep(0.02)
    except BaseException:
        sock.close()
        raise

    yield f"http://127.0.0.1:{port}"

    server.should_exit = True
    thread.join(timeout=10)
    # Без утверждения не остановившийся сервер молча уезжает в следующий
    # сценарий: порт занят, подмены хранилища указывают уже на чужой
    # tmp_path, а падает при этом посторонний тест.
    assert not thread.is_alive(), "сервер не остановился за 10 секунд"


@pytest.fixture
def browser_page(new_context):
    """Чистая вкладка браузера на каждый сценарий.

    Своё имя, а не ``page`` из pytest-playwright: у этой фикстуры есть
    обязанность, которой у плагинной нет, - она слышит исключения
    страницы. Всё остальное делает плагин.

    Контекст создаёт плагинная ``new_context``, а не браузер напрямую.

    Контекст новый, а не только вкладка: с ним обнуляется и
    ``localStorage``, в котором приложение держит выбранную тему.

    Необработанное исключение в скрипте страницы красит сценарий.

    Проверка стоит в разборке, поэтому pytest сообщает о ней как об
    ``ERROR`` теста, а не ``FAILED``. Для человека это одинаково красный;
    для мутационного стенда - ``прогон не состоялся`` вместо ``убит``
    (``tools/mutations.py``), поэтому стендом этот сторож не закрепляется
    и закрепиться не может: ``run_pytest`` считает строку ``ERROR``
    несостоявшимся прогоном и обрывает весь проход.
    """
    context = new_context()
    page = context.new_page()

    errors: list[str] = []
    page.on("pageerror", lambda error: errors.append(str(error)))

    def remember_console_error(message):
        """Запоминает ``console.error`` из скрипта, но не шум браузера.

        Аргументы отличают одно от другого. Playwright проводит через
        событие ``console`` не только настоящие вызовы из страницы
        (``Runtime.consoleAPICalled``), но и записи самого браузера из
        домена ``Log`` - в том числе «Failed to load resource» на каждый
        неуспешный HTTP-ответ. Такие записи он создаёт с пустым списком
        аргументов, освободив пришедшие от CDP; у вызова из скрипта
        аргументы настоящие.

        Собственный код приложения ``console.*`` не зовёт ни разу: ошибки
        API уходят в реактивное состояние и рендерятся в разметку.
        Поэтому непустые аргументы у сообщения уровня ``error`` означают
        ровно одно - Vue погасил исключение.
        """
        if message.type == "error" and message.args:
            errors.append(f"console.error: {message.text}")

    page.on("console", remember_console_error)

    yield page

    context.close()
    assert not errors, "страница уронила необработанное исключение: " + "; ".join(errors)
