"""Проверки разметки страниц, для которых не нужен браузер.

Текст статьи приходит с чужого сайта, поэтому выводится интерполяцией
Vue (``{{ ... }}``) - она экранирует разметку. Замена интерполяции на
``v-html`` включила бы исполнение чужого HTML в браузере пользователя.

Это сторож, а не проверка поведения. Он не доказывает, что экранирование
работает - за это отвечает Vue; он закрепляет решение никогда не
выводить чужой текст в обход него.

Поведение проверяет браузерный сценарий
``test_hostile_markup_from_a_saved_page_is_not_executed``
(``tests/e2e/test_smoke.py``): подставленная разметка видна
буквально, и ни одного её узла в DOM нет. Сценарий и сторож не дублируют
друг друга, потому что слепы в разные стороны. Сторож ищет подстроку и
потому не видит ``:innerHTML``, ``domProps`` и ``Vue.compile`` - они
дают тот же результат, не содержа ``v-html``. Сценарий смотрит на одну
страницу, одно поле и одну полезную нагрузку и потому не видит
``v-html``, появившийся у автора, названия сайта или в соседнем шаблоне.
Вместе они закрывают оба пункта, порознь - ни одного целиком.
"""

from pathlib import Path

import pytest

STATIC_DIR = Path(__file__).resolve().parent.parent / "static"
"""Каталог со страницами приложения."""

TEMPLATES = sorted(STATIC_DIR.glob("*.html"))
"""Все страницы, которые монтирует Vue."""


def test_templates_are_found():
    """Список шаблонов не пуст.

    Без этой проверки переименование каталога или расширения превращает
    сторож ниже в ноль тестов, и набор остаётся зелёным, не проверив
    ничего. Пустая выборка неотличима от прохождения - это ровно тот
    случай, когда молчание опаснее красного.
    """
    assert TEMPLATES


@pytest.mark.parametrize("template", TEMPLATES, ids=lambda path: path.name)
def test_template_does_not_render_foreign_markup(template):
    """Шаблон не выводит данные через ``v-html``.

    Атрибут ищется по всему файлу, а не только рядом с текстом статьи:
    к моменту, когда чужая разметка окажется в заголовке, авторе или
    названии сайта, отличать «безопасные» места от опасных будет поздно.
    """
    assert "v-html" not in template.read_text(encoding="utf-8")
